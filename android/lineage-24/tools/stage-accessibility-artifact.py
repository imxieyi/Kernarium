"""Stage the accessibility artifact in the AOSP workspace for the product.

The artifact is what dependencies/build-andarium-accessibility.sh writes on the
Mac: TalkBack.apk and eSpeakNG.apk, unsigned, and artifact.json naming each
APK's package and SHA-256 and the source trees they were built from. The tool
checks the artifact against its own description and writes
vendor/kernarium/accessibility: the two APKs and the Android.bp of the
filegroups that overlay/accessibility/Android.bp imports. A file whose bytes
did not change keeps its time, so an unchanged artifact rebuilds nothing.
Anything else the directory held is removed.

    stage-accessibility-artifact.py --artifact DIR --aosp-source DIR
    stage-accessibility-artifact.py --artifact DIR --check
"""

from __future__ import annotations

__import__("sys").dont_write_bytecode = True

import argparse
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path, PurePosixPath

DESTINATION = PurePosixPath("vendor/kernarium/accessibility")
# The artifact's APKs, the package each must be and the filegroup that names it.
APKS = {
    "TalkBack.apk": ("com.android.talkback", "kernarium_accessibility_talkback"),
    "eSpeakNG.apk": ("com.reecedunn.espeak", "kernarium_accessibility_espeak_ng"),
}
SOURCES = ("talkback", "espeak-ng", "sonic")
SCHEMA = 1


def fail(message: str) -> None:
    raise SystemExit(f"stage-accessibility-artifact.py: {message}")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def checked(artifact: Path) -> dict:
    """The artifact's description, once every file matches it."""
    if not artifact.is_absolute() or not artifact.is_dir() or artifact.is_symlink():
        fail(f"the artifact must be an absolute, regular directory: {artifact}")
    try:
        description = json.loads((artifact / "artifact.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        fail(f"cannot read artifact.json: {error}")
    if not isinstance(description, dict) or description.get("schema") != SCHEMA:
        fail(f"artifact.json is not schema {SCHEMA}")
    apks = description.get("apks")
    if not isinstance(apks, dict) or set(apks) != set(APKS):
        fail(f"artifact.json must describe exactly {', '.join(sorted(APKS))}")
    for name, (package, _) in APKS.items():
        entry = apks[name]
        path = artifact / name
        if not isinstance(entry, dict) or entry.get("package") != package:
            fail(f"{name} must be package {package}")
        if not re.fullmatch(r"[0-9a-f]{64}", str(entry.get("sha256"))):
            fail(f"{name} has no SHA-256 in artifact.json")
        if not path.is_file() or path.is_symlink():
            fail(f"{name} is missing from the artifact")
        if sha256(path) != entry["sha256"]:
            fail(f"{name} differs from artifact.json")
    trees = description.get("source_trees")
    if not isinstance(trees, dict) or set(trees) != set(SOURCES) or not all(
        re.fullmatch(r"[0-9a-f]{40}", str(tree)) for tree in trees.values()
    ):
        fail(f"artifact.json must record the trees of {', '.join(SOURCES)}")
    if not re.fullmatch(r"[0-9a-f]{64}", str(description.get("archives_sha256"))):
        fail("artifact.json must record the SHA-256 of the archive list it was built from")
    return description


def blueprint() -> bytes:
    groups = "".join(
        f'\nfilegroup {{\n    name: "{group}",\n    srcs: ["{name}"],\n}}\n' for name, (_, group) in sorted(APKS.items())
    )
    return (
        "// Generated by android/lineage-24/tools/stage-accessibility-artifact.py from the\n"
        "// accessibility artifact; overlay/accessibility/Android.bp imports these.\n" + groups
    ).encode()


def write(path: Path, content: bytes) -> None:
    """Writes `content` unless `path` already holds it, which keeps its time."""
    if path.is_file() and not path.is_symlink() and path.read_bytes() == content:
        return
    temporary = path.with_name(f".{path.name}.partial")
    temporary.write_bytes(content)
    temporary.replace(path)


def stage(artifact: Path, aosp_source: Path) -> None:
    if not aosp_source.is_absolute() or not (aosp_source / ".repo").is_dir():
        fail(f"--aosp-source must be an absolute AOSP Repo workspace: {aosp_source}")
    destination = aosp_source / DESTINATION
    if destination.is_symlink():
        fail(f"{DESTINATION} must not be a symbolic link")
    destination.mkdir(parents=True, exist_ok=True)
    wanted = {"Android.bp": blueprint(), "artifact.json": (artifact / "artifact.json").read_bytes()}
    for name in APKS:
        wanted[name] = (artifact / name).read_bytes()
    for entry in destination.iterdir():
        if entry.name not in wanted:
            shutil.rmtree(entry) if entry.is_dir() and not entry.is_symlink() else entry.unlink()
    for name, content in wanted.items():
        write(destination / name, content)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--artifact", type=Path, required=True)
    parser.add_argument("--aosp-source", type=Path)
    parser.add_argument("--check", action="store_true", help="check the artifact and stage nothing")
    args = parser.parse_args()
    if args.check == (args.aosp_source is not None):
        fail("give either --aosp-source or --check")
    description = checked(args.artifact)
    if args.check:
        print(f"accessibility artifact checks: {', '.join(sorted(description['apks']))}")
        return 0
    stage(args.artifact, args.aosp_source)
    print(f"staged the accessibility artifact in {DESTINATION}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
